// Generate imports at build time: adding one file exporting `definition` is sufficient.
// No runtime filesystem access or dynamic import paths in the browser bundle.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
const root = dirname(fileURLToPath(import.meta.url));
const files = (await readdir(root)).filter(file => file.endsWith('.ts') && !file.endsWith('.test.ts') && file !== 'registry.generated.ts').sort();
const definitions = [];
for (const file of files) {
  const source = await readFile(join(root, file), 'utf8');
  if (/export const definition\b/.test(source)) definitions.push(file.slice(0, -3));
}
const content = '// Generated by generate-registry.mjs. Do not edit by hand.\n' + definitions.map((file, i) => `import { definition as provider${i} } from './${file}';`).join('\n') + `\n\nexport const providerDefinitions = [${definitions.map((_, i) => `provider${i}`).join(', ')}] as const;\n`;
const target = join(root, 'registry.generated.ts');
if (await readFile(target, 'utf8').catch(() => '') !== content) await writeFile(target, content);
